import { test } from 'node:test';
import * as assert from 'node:assert/strict';
import { parseCommand, allSegments, normalizeProg, packageToProg, expandShortFlags, decodeEncodedCommand, hasHiddenUnicode, tokenize } from '../../../src/guard/parse';

const progs = (cmd: string, dialect: 'posix' | 'powershell' | 'cmd' = 'posix') => allSegments(parseCommand(cmd, { dialect })).map((s) => s.prog);
const first = (cmd: string, dialect: 'posix' | 'powershell' | 'cmd' = 'posix') => parseCommand(cmd, { dialect }).segments[0];

test('splits on operators and newlines, respects quotes', () => {
  assert.deepEqual(progs('a && b || c; d | e & f\ng'), ['a', 'b', 'c', 'd', 'e', 'f', 'g']);
  assert.deepEqual(first('echo "a && b"').args, ['a && b']);
  assert.deepEqual(first("echo 'a; b'").args, ['a; b']);
  assert.deepEqual(first('echo a\\ b').args, ['a b']);
  assert.deepEqual(first('echo "a\\"b"').args, ['a"b']);
  assert.deepEqual(first("echo 'it''s'").args, ['its']);
  assert.deepEqual(first('echo $\'a\\tb\'').args, ['a\tb']);
  assert.deepEqual(first('echo "x" y "z w"').args, ['x', 'y', 'z w']);
  assert.deepEqual(first('git "push" --force').args, ['push', '--force']);
  assert.deepEqual(first('echo a # comment').args, ['a']);
  assert.deepEqual(first('echo a#b').args, ['a#b']);
  assert.equal(parseCommand('').segments.length, 0);
  assert.equal(parseCommand('   \n  ').segments.length, 0);
});

test('redirects and heredocs', () => {
  const s = first('cat <<EOF > out.txt 2>&1\nhello\nworld\nEOF');
  assert.equal(s.prog, 'cat');
  assert.equal(s.heredoc, 'hello\nworld');
  assert.ok(s.redirects.some((r) => r.op === '>' && r.target === 'out.txt'));
  assert.ok(s.redirects.some((r) => r.op === '>&'));
  const t = first("cat <<'EOF'\n$HOME\nEOF");
  assert.equal(t.heredoc, '$HOME');
  const u = first('cat <<-EOF\n\thello\n\tEOF');
  assert.equal(u.heredoc, 'hello');
  const v = first('echo x >> a.log');
  assert.deepEqual(v.redirects.map((r) => [r.op, r.target]), [['>>', 'a.log']]);
  const w = first('cmd 2> err.txt');
  assert.equal(w.redirects[0].fd, 2);
  assert.equal(w.redirects[0].target, 'err.txt');
  const x = first('echo x &> all.txt');
  assert.equal(x.redirects[0].op, '&>');
  const y = first('sqlcmd -S h <<<"select 1"');
  assert.equal(y.redirects[0].op, '<<<');
  assert.equal(y.redirects[0].target, 'select 1');
  const z = first('cat < in.txt');
  assert.equal(z.redirects[0].op, '<');
  assert.equal(z.redirects[0].target, 'in.txt');
  const dyn = first('echo x > $OUT');
  assert.equal(dyn.redirects[0].dynamic, true);
});

