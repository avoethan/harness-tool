test('tokenizer edge cases do not throw', () => {
  const weird = ['"unterminated', "'unterminated", '$(unterminated', '`unterminated', '${unterminated', 'a <<', 'a <<EOF', '>', '>>', '|', '&&', '((', '))', '{', '}', '\\', 'a\\', '$', '$$', '2>&', '&>', '<(', 'cmd /c', 'pwsh -c', 'pwsh -enc', 'bash -c', 'docker exec', 'ssh', 'kubectl exec', 'npx', 'eval', 'find -exec', 'tmux send-keys', 'x'.repeat(10000)];
  for (const w of weird) {
    for (const d of ['posix', 'powershell', 'cmd'] as const) {
      assert.doesNotThrow(() => parseCommand(w, { dialect: d }), `${d}: ${w}`);
      assert.doesNotThrow(() => tokenize(w, d), `${d}: ${w}`);
    }
  }
});
