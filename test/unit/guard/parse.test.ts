test('remote and container wrappers record their target', () => {
  const d = first('docker exec -it -u root -e A=1 ctr sqlcmd -S localhost -Q q');
  assert.equal(d.prog, 'sqlcmd');
  assert.deepEqual(d.via, [{ kind: 'docker exec', target: 'ctr' }]);
  assert.deepEqual(d.env, { A: '1' });
  const r = first('docker run --rm --name n -v /a:/b -p 80:80 img sqlcmd -Q q');
  assert.equal(r.prog, 'sqlcmd');
  assert.equal(r.via[0].target, 'n');
  assert.equal(r.dockerImage, 'img');
  assert.deepEqual(r.dockerMounts, ['/a:/b']);
  const e = first('docker run --entrypoint sqlcmd img -Q q');
  assert.equal(e.prog, 'sqlcmd');
  assert.deepEqual(e.args, ['-Q', 'q']);
  const none = first('docker run -d --name db postgres');
  assert.equal(none.prog, 'docker');
  assert.equal(none.dockerImage, 'postgres');
  assert.equal(none.via[0].target, 'db');
  const c = first('docker compose exec -T svc psql -c q');
  assert.equal(c.prog, 'psql');
  assert.equal(c.via[0].target, 'svc');
  const dc = first('docker-compose exec svc psql -c q');
  assert.equal(dc.prog, 'psql');
  assert.equal(dc.via[0].target, 'svc');
  const unknown = first('docker exec --weird-flag ctr ls');
  assert.equal(unknown.opaque, true);
  const k = first('kubectl exec -n ns -it pod/x -c c -- sqlcmd -S y -Q q');
  assert.equal(k.prog, 'sqlcmd');
  assert.deepEqual(k.via, [{ kind: 'kubectl exec', target: 'x' }]);
  const k2 = first('kubectl exec mypod sqlcmd -Q q');
  assert.equal(k2.prog, 'sqlcmd');
  assert.equal(k2.via[0].target, 'mypod');
  assert.equal(first('kubectl get pods').prog, 'kubectl');
  const s = first('ssh -p 22 -i key user@host "git push --force"');
  assert.equal(s.prog, 'ssh');
  assert.equal(s.inner?.segments[0].prog, 'git');
  assert.deepEqual(s.inner?.segments[0].via, [{ kind: 'ssh', target: 'host' }]);
  const s2 = first('ssh host git push --force');
  assert.deepEqual(s2.inner?.segments[0].args, ['push', '--force']);
  const s3 = first('ssh host');
  assert.equal(s3.inner, undefined);
  const s4 = first('ssh host "$CMD"');
  assert.equal(s4.opaque, true);
  const nested = first('ssh host "docker exec ctr sqlcmd -Q q"');
  const inner = nested.inner!.segments[0];
  assert.equal(inner.prog, 'sqlcmd');
  assert.deepEqual(inner.via.map((v) => v.kind), ['ssh', 'docker exec']);
});

test('PowerShell: -Command, -EncodedCommand, call operator, script blocks, cmdlets', () => {
  const p = first('pwsh -NoProfile -c "Invoke-Sqlcmd -ServerInstance x -Query q; Get-Content .env | Out-File x"');
  assert.equal(p.prog, 'pwsh');
  assert.deepEqual(p.inner?.segments.map((s) => s.prog), ['invoke-sqlcmd', 'get-content', 'out-file']);
  assert.equal(p.inner?.segments[2].stdinFromPipe, true);
  assert.equal(p.inner?.dialect, 'powershell');
  const enc = Buffer.from('git push --force', 'utf16le').toString('base64');
  assert.equal(first('powershell -enc ' + enc).inner?.segments[0].prog, 'git');
  assert.equal(first('powershell -EncodedCommand ' + enc).inner?.segments[0].args[1], '--force');
  assert.equal(first('powershell -e ' + enc).inner?.segments[0].prog, 'git');
  assert.equal(first('powershell -ec ' + enc).inner?.segments[0].prog, 'git');
  assert.equal(first('powershell -enc not!!base64').opaque, true);
  assert.equal(decodeEncodedCommand(enc), 'git push --force');
  assert.equal(decodeEncodedCommand(''), null);
  assert.equal(first('pwsh -File x.ps1').inner, undefined);
  assert.equal(first('pwsh -f x.ps1').inner, undefined);
  assert.equal(first('pwsh -Command -').opaque, true);
  assert.equal(first('pwsh x.ps1').inner?.segments[0].prog, 'x.ps1');
  assert.equal(first('pwsh -ExecutionPolicy Bypass -NoLogo -NonInteractive -Command "ls"').inner?.segments[0].prog, 'ls');
  assert.equal(first('pwsh -c "& git push --force"').inner?.segments[0].prog, 'git');
  assert.equal(first('pwsh -c "& \'C:\\tools\\sqlcmd.exe\' -S x"').inner?.segments[0].prog, 'sqlcmd');
  const block = first('powershell -Command "& { Set-Content -Path x -Value y }"');
  assert.equal(block.inner?.segments[0].prog, 'scriptblock');
  assert.equal(block.inner?.segments[0].inner?.segments[0].prog, 'set-content');
  assert.equal(first('pwsh -c "$x = 1; git push -f"').inner?.segments[1].prog, 'git');
  assert.equal(first('pwsh -c "Invoke-Expression \'git push -f\'"').inner?.segments[0].inner?.segments[0].prog, 'git');
  assert.equal(first('pwsh -c "iex $cmd"').inner?.segments[0].opaque, true);
  assert.equal(first('pwsh -c "Start-Process git -ArgumentList \'push -f\'"').inner?.segments[0].inner?.segments[0].prog, 'git');
  assert.equal(first('pwsh -c "Invoke-Command -ComputerName h -ScriptBlock { git push -f }"').inner?.segments[0].inner?.segments[0].prog, 'git');
  assert.equal(first('pwsh -c "Invoke-Command -ComputerName h -ScriptBlock { git push -f }"').inner?.segments[0].inner?.segments[0].via[1]?.target, 'h');
  const here = first('pwsh -c @"\ngit push -f\n"@');
  assert.ok(here.inner);
  const ps = parseCommand('Get-Content .env | Out-File `\n x; $y = "a`tb"', { dialect: 'powershell' });
  assert.deepEqual(ps.segments.map((s) => s.prog), ['get-content', 'out-file', '']);
  assert.equal(ps.segments[1].args[0], 'x');
  const stop = parseCommand('sqlcmd --% -S x -Q "select 1"', { dialect: 'powershell' });
  assert.equal(stop.segments[0].prog, 'sqlcmd');
  const dot = parseCommand('. .\\script.ps1', { dialect: 'powershell' });
  assert.equal(dot.segments[0].prog, '.');
  const bt = parseCommand('echo `date`', { dialect: 'powershell' });
  assert.equal(bt.segments[0].subshells.length, 0);
});

test('cmd.exe: /c, separators, caret escapes, %VAR%, builtins', () => {
  const c = first('cmd /c "type .env & git push --force"');
  assert.equal(c.inner?.dialect, 'cmd');
  assert.deepEqual(c.inner?.segments.map((s) => s.prog), ['type', 'git']);
  assert.deepEqual(first('cmd.exe /d /s /c git push -f').inner?.segments[0].args, ['push', '-f']);
  assert.equal(first('cmd /k dir').inner?.segments[0].prog, 'dir');
  assert.equal(first('cmd /c del %APPDATA%\\devin\\config.json').inner?.segments[0].args[0], '%APPDATA%\\devin\\config.json');
  assert.equal(first('cmd /c del %APPDATA%\\devin\\config.json').inner?.segments[0].dynamic, true);
  assert.equal(first('cmd /c "cd /d C:\\x && del y"').inner?.segments[1].prog, 'del');
  assert.equal(first('cmd /c start /b git push -f').inner?.segments[0].inner?.segments[0].prog, 'git');
  assert.equal(first('cmd /c call git push -f').inner?.segments[0].prog, 'git');
  assert.equal(first('cmd /c %CMD%').inner?.segments[0].opaque, true);
  const esc = parseCommand('echo a^&b & dir', { dialect: 'cmd' });
  assert.equal(esc.segments.length, 2);
  assert.equal(esc.segments[0].args[0], 'a&b');
  const q = parseCommand('echo "a & b" && dir', { dialect: 'cmd' });
  assert.deepEqual(q.segments.map((s) => s.prog), ['echo', 'dir']);
  assert.equal(parseCommand('rem comment', { dialect: 'cmd' }).segments.length, 0);
  assert.equal(parseCommand('set X=1 & echo %X%', { dialect: 'cmd' }).segments[1].dynamic, true);
  assert.equal(parseCommand("echo it's", { dialect: 'cmd' }).segments[0].args[0], "it's");
  assert.equal(parseCommand('type nul > x', { dialect: 'cmd' }).segments[0].redirects[0].target, 'x');
});

test('command substitutions are parsed with their parent program', () => {
  const s = first('echo $(cat .env)');
  assert.equal(s.subshells.length, 1);
  assert.equal(s.subshells[0].segments[0].prog, 'cat');
  assert.equal(s.subshells[0].segments[0].parentProg, 'echo');
  const e = first('export $(cat .env | xargs)');
  assert.equal(e.subshells[0].segments[0].parentProg, 'export');
  assert.equal(e.subshells[0].segments[1].prog, 'echo');
  const b = first('echo `git push --force`');
  assert.equal(b.subshells[0].segments[0].args[1], '--force');
  const d = first('$(echo git) push --force');
  assert.equal(d.dynamicProg, true);
  assert.equal(d.opaque, true);
  assert.equal(d.subshells[0].segments[0].prog, 'echo');
  const n = first('echo "$(echo $(echo x))"');
  assert.equal(n.subshells[0].segments[0].subshells[0].segments[0].args[0], 'x');
  const ps = first('cat <(git push --force)');
  assert.equal(ps.subshells[0].segments[0].prog, 'git');
  const red = first('echo x > $(echo out)');
  assert.equal(red.subshells[0].segments[0].args[0], 'out');
  assert.equal(red.redirects[0].dynamic, true);
  const all = allSegments(parseCommand('a $(b `c`) && d | e'));
  assert.deepEqual(all.map((s) => s.prog), ['a', 'b', 'c', 'd', 'e']);
  const inner = allSegments(parseCommand('bash -c "x $(y)"'));
  assert.deepEqual(inner.map((s) => s.prog), ['bash', 'x', 'y']);
});

