/**
 * Scoped rule files (DESIGN 2.4): advisory detail per repo, loaded by the
 * agent only around that repo's files. They carry the ledger's statements and
 * fix texts for that repo, never safety rules (those are rails: hooks and
 * permissions, which a lazily loaded file cannot guarantee, R-56).
 *
 *   team      Devin  ~/.devin/rules/<repo>.md     front matter `trigger: glob`, `globs` (a YAML list: Devin CLI rejects a string)
 *             Claude ~/.claude/rules/<repo>.md    front matter `paths:`
 *             Codex  none (the hooks inject standards at the point of use)
 *   personal  Devin  .devin/rules/<name>.md, Claude .claude/rules/<name>.md,
 *             Codex  nested AGENTS.md in the folders a path-scoped standard covers
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import type { AgentId, LedgerRecord } from '../types';
import { recordAppliesTo } from '../discover/checks';
import { renderFrontMatter } from '../lib/frontmatter';
import { sha256 } from '../lib/hash';
import { slug } from '../lib/paths';
import { allRepoFacts, clip, posix, type RenderContext, type RenderedFile, type RepoFacts } from './model';

const MAX_RECORDS = 40;

/** The path globs of a record that apply to one repo (repo-qualified `<repoId>:<glob>` or plain). */
export function pathScopesFor(r: LedgerRecord, repoId: string): string[] {
  const paths = r.scope.paths ?? [];
  const qualified = paths.filter((p) => /^[^/*:]+:/.test(p));
  const mine = qualified.filter((p) => p.startsWith(repoId + ':')).map((p) => p.slice(repoId.length + 1));
  if (mine.length) return mine;
  return paths.filter((p) => !qualified.includes(p));
}

/** Ledger records that hold for a repo (any path in it), minus safety records. */
export function recordsForRepo(ctx: RenderContext, repoId: string): LedgerRecord[] {
  return (ctx.ledger?.records ?? []).filter((r) => {
    if (r.family === 'safety') return false;
    if (!r.scope.repos.includes('*') && !r.scope.repos.includes(repoId)) return false;
    const scopes = pathScopesFor(r, repoId);
    // a record whose qualified globs all name other repos does not hold here
    if ((r.scope.paths ?? []).length && !scopes.length) return recordAppliesTo(r, repoId, '');
    return true;
  });
}

function recordLine(r: LedgerRecord): string {
  const fix = r.check.fixText ? ` Fix: ${clip(r.check.fixText, 180)}` : '';
  return `- ${clip(r.statement, 220)}${fix} (\`${r.id}\`, ${r.tier})`;
}

function body(title: string, records: LedgerRecord[], note: string): string {
  const lines = [
    '<!-- Generated by harness from the standards ledger; advisory. The checks and the gate enforce these. -->',
    `# ${title}`,
    '',
    note,
    '',
  ];
  const list = records.slice(0, MAX_RECORDS);
  for (const r of list) lines.push(recordLine(r));
  if (records.length > list.length) lines.push(`- ${records.length - list.length} more: \`harness discover\` lists them in its report.`);
  return lines.join('\n') + '\n';
}

interface Group {
  /** Repo-relative globs; empty = the whole repo. */
  globs: string[];
  records: LedgerRecord[];
}

function groupsFor(ctx: RenderContext, f: RepoFacts): Group[] {
  const recs = recordsForRepo(ctx, f.id);
  const whole: LedgerRecord[] = [];
  const byGlob = new Map<string, Group>();
  for (const r of recs) {
    const scopes = pathScopesFor(r, f.id);
    if (!scopes.length) {
      whole.push(r);
      continue;
    }
    const key = [...scopes].sort().join(',');
    const g = byGlob.get(key) ?? { globs: [...scopes].sort(), records: [] };
    g.records.push(r);
    byGlob.set(key, g);
  }
  const out: Group[] = [];
  if (whole.length) out.push({ globs: [], records: whole });
  out.push(...[...byGlob.values()].sort((a, b) => a.globs.join().localeCompare(b.globs.join())));
  return out;
}

/** The folder a glob is rooted at (`packages/api/**` -> `packages/api`), or '' for a glob that starts with a wildcard. */
export function globDir(glob: string): string {
  const segs = posix(glob).split('/');
  const out: string[] = [];
  for (const s of segs) {
    if (/[*?[\]{}]/.test(s)) break;
    out.push(s);
  }
  // a last segment with a dot and no wildcard is a file, not a folder
  if (out.length === segs.length && out.length && /\.[^/]+$/.test(out[out.length - 1])) out.pop();
  return out.join('/');
}

function devinRule(file: string, globs: string[], text: string, agent: AgentId, origin: string): RenderedFile {
  const fm = renderFrontMatter({ trigger: 'glob', globs });
  const content = fm + text;
  return { path: file, kind: 'text', content, role: 'scoped', agent, hunks: [{ checkId: 'render.scoped', reason: `advisory standards for ${origin}, loaded around those files`, provenance: 'ledger', contentHash: sha256(content) }] };
}

function claudeRule(file: string, globs: string[], text: string, agent: AgentId, origin: string): RenderedFile {
  const fm = renderFrontMatter({ paths: globs });
  const content = fm + text;
  return { path: file, kind: 'text', content, role: 'scoped', agent, hunks: [{ checkId: 'render.scoped', reason: `advisory standards for ${origin}, loaded around those files`, provenance: 'ledger', contentHash: sha256(content) }] };
}

export function renderScoped(ctx: RenderContext): RenderedFile[] {
  const out: RenderedFile[] = [];
  const facts = allRepoFacts(ctx);
  const devin = ctx.agents.includes('devin');
  const claude = ctx.agents.includes('claude');
  const codex = ctx.agents.includes('codex');
  if (ctx.setting === 'team') {
    for (const f of facts) {
      for (const g of groupsFor(ctx, f)) {
        const rel = f.relPath === '.' ? '' : f.relPath.replace(/\/+$/, '') + '/';
        const globs = g.globs.length ? g.globs.map((x) => `**/${rel}${x}`) : [`**/${rel}**`];
        const suffix = g.globs.length ? '-' + slug(g.globs.map(globDir).filter(Boolean).join('-') || 'paths') : '';
        const name = `${slug(f.name)}${suffix}.md`;
        const title = `${f.name}${g.globs.length ? ` (${g.globs.join(', ')})` : ''}: standards`;
        const text = body(title, g.records, `Standards discovered in ${f.name} with their evidence tier. They hold for the files under ${g.globs.length ? g.globs.map((x) => '`' + x + '`').join(', ') : 'the whole repository'}.`);
        if (devin) out.push(devinRule(path.join(ctx.userHome, '.devin', 'rules', name), globs, text, 'devin', f.name));
        if (claude) out.push(claudeRule(path.join(ctx.userHome, '.claude', 'rules', name), globs, text, 'claude', f.name));
      }
    }
    return out;
  }
  // personal: the one repository
  const root = ctx.repoRoot ?? ctx.workspaceRoot;
  const f = facts.find((x) => path.resolve(x.path) === path.resolve(root)) ?? facts[0];
  if (!f) return out;
  for (const g of groupsFor(ctx, f)) {
    const name = g.globs.length ? `standards-${slug(g.globs.map(globDir).filter(Boolean).join('-') || 'paths')}.md` : 'standards.md';
    const globs = g.globs.length ? g.globs : ['**/*'];
    const title = g.globs.length ? `Standards for ${g.globs.join(', ')}` : 'Standards of this repository';
    const text = body(title, g.records, `Discovered with evidence; they hold for ${g.globs.length ? g.globs.map((x) => '`' + x + '`').join(', ') : 'every file here'}.`);
    if (devin) out.push(devinRule(path.join(root, '.devin', 'rules', name), globs, text, 'devin', g.globs.join(', ') || f.name));
    if (claude) out.push(claudeRule(path.join(root, '.claude', 'rules', name), globs, text, 'claude', g.globs.join(', ') || f.name));
    if (codex && g.globs.length) {
      // Codex reads one AGENTS.md per folder from the git root down to the working folder.
      const dirs = [...new Set(g.globs.map(globDir).filter(Boolean))];
      for (const d of dirs) {
        const abs = path.join(root, d);
        if (!fs.existsSync(abs) || !fs.statSync(abs).isDirectory()) continue;
        const blockText = body(`Standards for \`${d}/\``, g.records, 'Discovered with evidence; advisory (the checks and the gate enforce them).').replace(/^<!--.*-->\n/, '');
        out.push({
          path: path.join(abs, 'AGENTS.md'),
          kind: 'block',
          block: { style: 'md', position: 'end' },
          content: blockText,
          role: 'scoped',
          agent: 'codex',
          hunks: [{ checkId: 'render.scoped', reason: `advisory standards for ${d}/ (Codex reads nested AGENTS.md files)`, provenance: 'ledger', contentHash: sha256(blockText) }],
        });
      }
    }
  }
  return out;
}
